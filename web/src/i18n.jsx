const I18nCtx = createContext(null);

export function I18nProvider({ children }) {
  const [lang, setLangState] = useState(() => localStorage.getItem('lang') || 'ru');

  useEffect(() => {
    localStorage.setItem('lang', lang);
    document.documentElement.lang = lang;
    setUtilLang(lang);
  }, [lang]);

  const t = (key, vars) => {
    let s = (T[lang] && T[lang][key]) ?? T.ru[key] ?? key;
    if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? vars[k] : ''));
    return s;
  };

  return <I18nCtx.Provider value={{ lang, setLang: setLangState, t }}>{children}</I18nCtx.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nCtx);
  if (!ctx) throw new Error('useI18n вне I18nProvider');
  return ctx;
}

export function LanguageSelect() {
  const { lang, setLang } = useI18n();
  return (
    <select className="lang-select" value={lang} onChange={(e) => setLang(e.target.value)} title="Language">
      {LANGS.map((l) => (
        <option key={l.code} value={l.code}>
          {l.name}
        </option>
      ))}
    </select>
  );
}
